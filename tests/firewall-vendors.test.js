test('PAN-OS, FortiOS, MikroTik, OPNsense, Junos and iptables policies convert to the firewall rule shape without guessing objects', () => {
  const p = panosRules(panos);
  assert.deepEqual(p.rules.map(r => [r.name, r.action, r.dst_ports.join(','), r.filters_readable]), [['allow-rdp-any', 'allow', '3389', true], ['web-app-default', 'allow', 'any', false], ['deny-all', 'deny', 'any', true]]);
  assert.deepEqual(p.rules[0].scope_constraints, ['src-zone:untrust', 'dst-zone:trust']);
  const f = fortiosPolicies(fortios);
  assert.deepEqual(f.rules.map(r => [r.dst_ports.join(','), r.enabled, r.filters_readable]), [['22', true, true], ['any', false, false]]);
  const m = mikrotikFilter(mikrotik);
  assert.equal(m.rules.length, 4, 'NAT chains are not filter rules'); assert.deepEqual(m.rules[1].dst_ports, ['8291']); assert.equal(m.rules[2].filters_readable, false, 'address lists are named objects');
  const o = opnsenseRules(opnsense);
  assert.deepEqual(o.rules.map(r => [r.action, r.enabled, r.dst.join(',')]), [['allow', true, '192.0.2.10'], ['deny', false, 'any']]);
  const j = junosSetPolicies(junos);
  assert.deepEqual(j.rules.map(r => [r.name, r.dst_ports.join(','), r.filters_readable]), [['allow-ssh', '22', true], ['custom', 'any', false]]);
  const i = iptablesSave(iptables);
  assert.deepEqual(i.rules.map(r => r.name), ['INPUT ACCEPT', 'INPUT ACCEPT 22', 'INPUT ACCEPT 5432', 'INPUT DROP', 'INPUT default policy DROP', 'FORWARD default policy DROP']);
  assert.deepEqual(i.rules[2].src, ['10.0.0.0/8']); assert.equal(i.rules[3].filters_readable, false, 'ipset match sets are named objects');
  for (const [fn, bad] of [[panosRules, {}], [fortiosPolicies, {}], [mikrotikFilter, {}], [opnsenseRules, {}], [junosSetPolicies, 'x'], [iptablesSave, 'x']]) assert.throws(() => fn(bad));
});

test('vendor rulesets are analysed by the CG-020 firewall analyzer', t => {
  const s = new Store(':memory:'); t.after(() => s.close());
  const d = new Domain(s, { clock: () => Date.parse('2026-11-18T06:00:00.000Z') });
  s.run('INSERT INTO users VALUES (?,?,?,?,?)', 'admin-a', 'admin-a', 'fixture-not-a-password-hash', 'admin', '2026-11-18T06:00:00.000Z');
  const source = d.createSource('admin-a', { name: 'Firewall policies', stale_seconds: 3600 }), at = '2026-11-18T06:00:00.000Z';
  const ev = (id, vendor, rules) => ({ event_id: id, kind: 'firewall.ruleset', observed_at: at, asset: { external_id: `fw-${id}`, hostname: id, os_family: 'network', device_type: 'firewall', addresses: [] }, details: { ruleset_id: `${vendor}:${id}`, device_ref: id, vendor, evaluation: 'first-match', rules } });
  d.ingest('admin-a', source.id, { schema_version: 'cg.telemetry/1', events: [ev('pa', 'palo-alto', panosRules(panos).rules), ev('fgt', 'fortigate', fortiosPolicies(fortios).rules), ev('mt', 'mikrotik', mikrotikFilter(mikrotik).rules), ev('opn', 'opnsense', opnsenseRules(opnsense).rules), ev('srx', 'juniper-srx', junosSetPolicies(junos).rules), ev('lin', 'iptables', iptablesSave(iptables).rules)] });
  const a = d.firewallRuleAnalysis();
  assert.equal(a.items.length, 6);
  assert.ok(a.items.find(x => x.vendor === 'palo-alto').findings.some(f => /3389/.test(JSON.stringify(f))), 'RDP from any is reported');
  assert.ok(a.items.find(x => x.vendor === 'mikrotik').findings.length > 0, 'Winbox open to any is reported');
});
